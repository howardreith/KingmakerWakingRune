<#
.SYNOPSIS
  Resolves data\quartermaster.csv against a recon items.txt dump and generates the stock table and catalogue doc.
.DESCRIPTION
  A name matching several blueprints resolves to its highest-cost entry (cheap duplicates are quest or
  placeholder copies); use guid:<hex> to pin one explicitly.
#>
[CmdletBinding()]
param([Parameter(Mandatory = $true)] [string] $ItemsDump)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$byName = @{}
$byGuid = @{}
foreach ($line in [IO.File]::ReadAllLines($ItemsDump)) {
    $p = $line.Split('|')
    if ($p.Count -lt 5) { continue }
    $entry = [pscustomobject]@{ Class = $p[0]; Guid = $p[1]; Name = $p[2]; Display = $p[3]; Cost = [int]($p[4] -replace 'cost=', '') }
    $byGuid[$entry.Guid] = $entry
    if (-not $byName.ContainsKey($entry.Name)) { $byName[$entry.Name] = New-Object System.Collections.ArrayList }
    [void]$byName[$entry.Name].Add($entry)
}
$section = 'General'
$rows = New-Object System.Collections.ArrayList
$missing = New-Object System.Collections.ArrayList
foreach ($line in [IO.File]::ReadAllLines((Join-Path $Root 'data\quartermaster.csv'))) {
    if ($line -match '^#\s*(.+)$') { if ($line -notmatch 'AssetName') { $section = $Matches[1] }; continue }
    if (-not $line.Trim()) { continue }
    $key, $count = $line.Split(',')
    $hit = $null
    if ($key -like 'guid:*') { $g = $key.Substring(5); if ($byGuid.ContainsKey($g)) { $hit = $byGuid[$g] } }
    elseif ($byName.ContainsKey($key)) { $hit = @($byName[$key] | Sort-Object Cost -Descending)[0] }
    if (-not $hit) { [void]$missing.Add($key); continue }
    [void]$rows.Add([pscustomobject]@{ Section = $section; Hit = $hit; Count = [int]$count })
}
if ($missing.Count) { Write-Warning ("Not in this game, skipped: " + ($missing -join ', ')) }
$dupes = @($rows | Group-Object { $_.Hit.Guid } | Where-Object Count -gt 1)
if ($dupes.Count) { throw "Duplicate blueprints: $(($dupes | ForEach-Object Name) -join ', ')" }

$cs = New-Object System.Text.StringBuilder
[void]$cs.AppendLine('// Generated by scripts\GenerateStock.ps1 from data\quartermaster.csv; edit the CSV, not this file.')
[void]$cs.AppendLine('namespace KingmakerWakingRune.Blueprints')
[void]$cs.AppendLine('{')
[void]$cs.AppendLine('    internal static class QuartermasterCatalogue')
[void]$cs.AppendLine('    {')
[void]$cs.AppendLine('        public static readonly CatalogueEntry[] Items =')
[void]$cs.AppendLine('        {')
foreach ($r in $rows) { [void]$cs.AppendLine(('            new CatalogueEntry("{0}", {1}), // {2}' -f $r.Hit.Guid, $r.Count, $r.Hit.Display)) }
[void]$cs.AppendLine('        };')
[void]$cs.AppendLine('    }')
[void]$cs.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $Root 'src\KingmakerWakingRune\Blueprints\QuartermasterCatalogue.cs'), $cs.ToString())

$total = ($rows | Measure-Object Count -Sum).Sum
$md = New-Object System.Text.StringBuilder
[void]$md.AppendLine('# Quartermaster catalogue')
[void]$md.AppendLine()
[void]$md.AppendLine("The CSV catalogue of the Society Quartermaster in the Magnimar Lodge: $($rows.Count) lines, $total items, generated from ``data/quartermaster.csv`` against installed game data (2.1.7b). In game the shop also stocks a scroll of every Wizard spell of levels 0-6 (99 each) and, when it is enabled, the optional Tabletop Rules Expansion lines; see ``docs/WR-PLAYTEST-01-STOCK.md`` for the full in-game audit.")
[void]$md.AppendLine()
[void]$md.AppendLine("**Pricing:** native vendor rules with no price overrides. Buying costs each item's ``Cost`` (listed below). Selling pays ``Cost x BlueprintRoot.Vendors.SellModifier``, so buying then re-selling always loses money. An item sold to the vendor joins its stock. Stock lives in the save (``Player.SharedVendorTables``); a catalogue change reaches a visited shop once, by the native difference (new lines arrive, a removed retail line leaves, sold goods stay). **Resupply:** when the shop opens, any line whose shelf count is below its catalogue count is topped up to it with new merchant stock; nothing above it changes.")
[void]$md.AppendLine()
[void]$md.AppendLine("**Deliberate omissions:** named or quest items, artifacts, kingdom rewards and developer copies; inherent-bonus tomes and manuals; weapons and armor above +3 (the one exception is the +4 composite longbow, because the game has no +2/+3 composite longbow blueprint); +6 stat items; greater metamagic rods and the normal Quicken rod; Gloves of Dexterity (owner policy, WR-PLAYTEST-01). Tabletop items absent from Kingmaker are not added. **Quantities:** at least 12 of every equipment line, 99 of every potion and scroll, 24 of every wand, 999 diamond dust.")
[void]$md.AppendLine()
foreach ($g in $rows | Group-Object Section) {
    [void]$md.AppendLine("## $($g.Name)")
    [void]$md.AppendLine()
    [void]$md.AppendLine('| Item | Stock | Price (gp) | Blueprint |')
    [void]$md.AppendLine('|---|---:|---:|---|')
    foreach ($r in $g.Group) { [void]$md.AppendLine(('| {0} | {1} | {2:N0} | `{3}` |' -f $r.Hit.Display, $r.Count, $r.Hit.Cost, $r.Hit.Guid)) }
    [void]$md.AppendLine()
}
[IO.File]::WriteAllText((Join-Path $Root 'docs\QUARTERMASTER.md'), $md.ToString())
Write-Host "Generated $($rows.Count) stock lines ($total items); missing $($missing.Count)."
